WEIGHTS = [cluster["weight"] for cluster in CLUSTERS]


def choose_cluster() -> dict:
    return random.choices(CLUSTERS, weights=WEIGHTS, k=1)[0]


def random_point(cluster: dict) -> tuple[float, float]:
    lat = random.gauss(cluster["lat"], cluster["sigma"])
    lon_sigma = cluster["sigma"] / max(0.3, math.cos(math.radians(cluster["lat"])))
    lon = random.gauss(cluster["lon"], lon_sigma)
    return round(lat, 6), round(lon, 6)


def random_road(cluster: dict) -> str:
    return random.choice(cluster["roads"])


def demo_hubs() -> list[dict]:
    """One synthetic response hub per governorate for the live demo.

    The live feed covers the whole country, so a Cairo-only tenant list would
    make every case outside the capital impossible to assign. These hubs are
    not claims on the curated registry; they are clearly labelled demo
    facilities that let the live map exercise dispatch, routing and handover
    in every governorate.
    """
    by_governorate: dict[str, dict] = {}
    for cluster in CLUSTERS:
        current = by_governorate.get(cluster["governorate"])
        if current is None or cluster["weight"] > current["weight"]:
            by_governorate[cluster["governorate"]] = cluster

    hubs = []
    for index, cluster in enumerate(
        sorted(by_governorate.values(), key=lambda item: item["governorate"]), start=1
    ):
        hubs.append(
            {
                "code": f"demo-hub-{index:02d}",
                "name": f"{cluster['city']} Emergency Hospital",
                "governorate": cluster["governorate"],
                "city": cluster["city"],
                "lat": cluster["lat"],
                "lon": cluster["lon"],
                "address": f"National demo response hub, {cluster['city']}, {cluster['governorate']}",
            }
        )
    return hubs
